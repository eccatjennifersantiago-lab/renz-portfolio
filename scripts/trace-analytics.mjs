// Traces the daily-views line from the YouTube Studio screenshot so the site
// can draw it as an animated chart. No values are invented: each day is read
// from the line's pixel position, then the series is scaled so its total
// matches the real 191,536,536 views shown in the same screenshot.
//
// Usage: node scripts/trace-analytics.mjs [screenshot.png]
// Writes src/data/views-series.ts
import sharp from "sharp";
import { writeFile } from "node:fs/promises";

const SRC = process.argv[2] ?? "public/images/youtube-analytics.png";
const TOTAL_VIEWS = 191_536_536;
const DAYS = 365;

// Chart geometry measured from the screenshot (1659 x 1101):
// gridlines 9M / 6M / 3M at y = 566.5 / 629.5 / 692.5, so 0 sits at 755.5;
// the line runs from x = 97 (Oct 16, 2025) to x = 1459 (Oct 15, 2026).
const X0 = 97;
const X1 = 1459;
const Y_ZERO = 755.5;
const PX_PER_3M = 63;
const Y_TOP = 540;
const Y_BOTTOM = 760;

const { data, info } = await sharp(SRC).removeAlpha().raw().toBuffer({ resolveWithObject: true });
const W = info.width;
const isLine = (r, g, b) => b > 150 && g > 120 && r < 130 && b - r > 70;

/** Centre of the line in one pixel column, or null if none. */
function lineY(x) {
  let sum = 0;
  let count = 0;
  for (let y = Y_TOP; y <= Y_BOTTOM; y++) {
    const i = (y * W + x) * 3;
    if (isLine(data[i], data[i + 1], data[i + 2])) {
      sum += y;
      count++;
    }
  }
  return count ? sum / count : null;
}

const pxPerDay = (X1 - X0) / (DAYS - 1);
const raw = [];
for (let d = 0; d < DAYS; d++) {
  // Studio plots one point per day; read the column at that day's position.
  const x = Math.round(X0 + d * pxPerDay);
  const y = lineY(x) ?? lineY(x - 1) ?? lineY(x + 1) ?? Y_ZERO;
  raw.push(Math.max(0, ((Y_ZERO - y) / PX_PER_3M) * 3_000_000));
}

const tracedTotal = raw.reduce((a, b) => a + b, 0);
const scale = TOTAL_VIEWS / tracedTotal;
const series = raw.map((v) => Math.round((v * scale) / 1000) * 1000);

const out = `// Generated by scripts/trace-analytics.mjs. Do not edit by hand.
// Daily views traced from the YouTube Studio screenshot (Oct 16, 2025 to
// Oct 15, 2026) and scaled to the real 365-day total of ${TOTAL_VIEWS.toLocaleString("en-US")}.
// Individual days are approximate (read from pixel positions).
export const viewsSeries = {
  start: "2025-10-16",
  traced: true,
  values: [${series.join(", ")}],
} as const;
`;
await writeFile("src/data/views-series.ts", out);
console.log(
  `Traced ${DAYS} days. Raw traced total ${Math.round(tracedTotal).toLocaleString("en-US")} ` +
    `vs real ${TOTAL_VIEWS.toLocaleString("en-US")} (scale ${scale.toFixed(3)}). ` +
    `Peak ≈ ${Math.max(...series).toLocaleString("en-US")}.`,
);
